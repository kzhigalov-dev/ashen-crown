// Насколько враги каждого следующего уровня мира крепче и больнее бьют.
const POWER_STEP = 0.08;

// Все уровни игры по порядку прохождения.
//   world, worldName — мир; number — номер уровня в мире (1…5);
//   power — множитель здоровья и урона обычных врагов;
//   boss  — страж (только у пятого уровня мира).
export const LEVELS = WORLDS.flatMap((world) =>
    world.levels.map((level, index) => ({
        id: `${world.id}-${index + 1}`,
        name: level.name,
        world: world.id,
        worldName: world.name,
        number: index + 1,
        power: 1 + index * POWER_STEP,
        boss: level.parts.includes('arena') ? world.boss : null,
        theme: world.theme,
        segments: level.parts.map((part) => world.parts[part]),
    }))
);
